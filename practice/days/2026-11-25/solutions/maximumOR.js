var maximumOr = function(nums, k) {
  const n = nums.length;
  const suff = new Int32Array(n + 1);
  for (let i = n - 1; i >= 0; i--) {
    suff[i] = suff[i + 1] | nums[i];
  }
  let pref = 0;
  let ans = 0n;
  const shift = BigInt(k);
  for (let i = 0; i < n; i++) {
    const other = BigInt(pref | suff[i + 1]);
    const cand = other | (BigInt(nums[i]) << shift);
    if (cand > ans) ans = cand;
    pref |= nums[i];
  }
  return Number(ans);
};
