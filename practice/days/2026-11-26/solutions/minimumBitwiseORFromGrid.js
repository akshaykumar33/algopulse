var minimumOR = function(grid) {
  const m = grid.length;
  let mask = (1 << 17) - 1;
  for (let b = 16; b >= 0; b--) {
    const test = mask & ~(1 << b);
    let ok = true;
    for (let i = 0; i < m; i++) {
      const row = grid[i];
      let rowOk = false;
      for (let j = 0; j < row.length; j++) {
        if ((row[j] | test) === test) {
          rowOk = true;
          break;
        }
      }
      if (!rowOk) {
        ok = false;
        break;
      }
    }
    if (ok) mask = test;
  }
  return mask;
};
