/**
 * LeetCode Problem Solution: Best Time to Buy and Sell Stock
 */
var maxProfit = function(prices) {
  let min = Infinity;
  let maxP = 0;
  for (let i = 0; i < prices.length; i++) {
    if (prices[i] < min) {
      min = prices[i];
    } else if (prices[i] - min > maxP) {
      maxP = prices[i] - min;
    }
  }
  return maxP;
};

var solve = function(prices) {
  return maxProfit(prices);
};

