var maxPoints = function(technique1, technique2, k) {
  const n = technique1.length;
  const diff = new Array(n);
  for (let i = 0; i < n; i++) {
    diff[i] = [technique1[i] - technique2[i], i];
  }
  diff.sort((a, b) => b[0] - a[0]);
  let ans = 0;
  for (let i = 0; i < k; i++) {
    ans += technique1[diff[i][1]];
  }
  for (let i = k; i < n; i++) {
    const idx = diff[i][1];
    ans += technique1[idx] > technique2[idx] ? technique1[idx] : technique2[idx];
  }
  return ans;
};
