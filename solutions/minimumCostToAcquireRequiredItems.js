var minimumCost = function(cost1, cost2, costBoth, need1, need2) {
  if (costBoth >= cost1 + cost2) {
    return need1 * cost1 + need2 * cost2;
  }
  const common = need1 < need2 ? need1 : need2;
  let ans = common * costBoth;
  if (need1 > need2) {
    const rem = need1 - need2;
    const c = cost1 < costBoth ? cost1 : costBoth;
    ans += rem * c;
  } else if (need2 > need1) {
    const rem = need2 - need1;
    const c = cost2 < costBoth ? cost2 : costBoth;
    ans += rem * c;
  }
  return ans;
};
